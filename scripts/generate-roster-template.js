const path = require('path');
const ExcelJS = require('exceljs');

const outputPath = path.join(process.cwd(), 'public', 'templates', 'AIT-roster-template.xlsx');
const MAX_DATA_ROWS = 10000;
const branches = ['AIML', 'CT', 'EE', 'ME', 'CE', 'E&C'];
const years = ['First Year', 'Second Year', 'Third Year', 'Final Year'];

async function main() {
    const workbook = new ExcelJS.Workbook();
    workbook.creator = 'AIT Placement Portal';
    workbook.subject = 'Roster import template';
    workbook.description = 'PRN-safe roster template generated by scripts/generate-roster-template.js';

    const sheet = workbook.addWorksheet('Roster', {
        views: [{ state: 'frozen', ySplit: 1 }]
    });

    sheet.columns = [
        { header: 'prn', key: 'prn', width: 22, style: { numFmt: '@' } },
        { header: 'name', key: 'name', width: 34 },
        { header: 'dob', key: 'dob', width: 16, style: { numFmt: '@' } },
        { header: 'branch', key: 'branch', width: 14 },
        { header: 'class', key: 'class', width: 16 },
        { header: 'year', key: 'year', width: 18 }
    ];

    const header = sheet.getRow(1);
    header.font = { bold: true };
    header.alignment = { vertical: 'middle' };
    header.height = 22;
    header.eachCell(cell => {
        cell.protection = { locked: true };
    });

    sheet.getCell('A1').note = 'PRN is an identifier. Enter the exact 10–20 digits. This column is permanently formatted as Text so Excel cannot round long PRNs.';
    sheet.getCell('C1').note = 'Enter DOB as DD-MM-YYYY. This column is formatted as Text to preserve the value exactly.';
    sheet.getCell('D1').note = `Allowed values: ${branches.join(', ')}`;
    sheet.getCell('E1').note = 'Class/division: 1–20 letters, numbers, spaces, or hyphens. Example: BE-A.';
    sheet.getCell('F1').note = `Allowed values: ${years.join(', ')}`;

    // Column-level text formatting is the important guard: newly typed PRNs remain text.
    sheet.getColumn('A').numFmt = '@';
    sheet.getColumn('C').numFmt = '@';

    sheet.dataValidations.add(`D2:D${MAX_DATA_ROWS + 1}`, {
        type: 'list',
        allowBlank: false,
        formulae: [`"${branches.join(',')}"`],
        showErrorMessage: true,
        errorStyle: 'stop',
        errorTitle: 'Invalid branch',
        error: `Use one of: ${branches.join(', ')}`
    });
    sheet.dataValidations.add(`F2:F${MAX_DATA_ROWS + 1}`, {
        type: 'list',
        allowBlank: false,
        formulae: [`"${years.join(',')}"`],
        showErrorMessage: true,
        errorStyle: 'stop',
        errorTitle: 'Invalid year',
        error: `Use one of: ${years.join(', ')}`
    });

    sheet.autoFilter = 'A1:F1';
    await workbook.xlsx.writeFile(outputPath);

    // Re-open the generated file so CI fails if ExcelJS produced an unreadable workbook
    // or if the PRN text-format contract regresses.
    const verification = new ExcelJS.Workbook();
    await verification.xlsx.readFile(outputPath);
    const verifySheet = verification.getWorksheet('Roster');
    if (!verifySheet) throw new Error('Generated roster workbook has no Roster sheet.');
    if (verifySheet.getColumn('A').numFmt !== '@') throw new Error('Generated PRN column is not formatted as Text.');
    if (verifySheet.getColumn('C').numFmt !== '@') throw new Error('Generated DOB column is not formatted as Text.');
    if (!verifySheet.dataValidations.model[`D2:D${MAX_DATA_ROWS + 1}`]) throw new Error('Generated branch validation is missing.');
    if (!verifySheet.dataValidations.model[`F2:F${MAX_DATA_ROWS + 1}`]) throw new Error('Generated year validation is missing.');

    console.log(`Generated PRN-safe roster template at ${outputPath}`);
}

main().catch(error => {
    console.error(error);
    process.exitCode = 1;
});
